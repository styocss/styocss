import process from 'node:process'
import { fileURLToPath } from 'node:url'
import { chromium } from 'playwright'
import { preview } from 'vite'

const PROBE_DESCRIPTION = 'Playground sync smoke probe'
const READY_TIMEOUT_MS = 240_000
const PLAYGROUND_ROOT = fileURLToPath(new URL('..', import.meta.url))

function assert(condition, message) {
	if (!condition)
		throw new Error(message)
}

let previewServer = null
let baseUrl = process.env.PLAYGROUND_SYNC_URL
if (!baseUrl) {
	previewServer = await preview({ root: PLAYGROUND_ROOT, preview: { host: '127.0.0.1' } })
	const previewBase = previewServer.resolvedUrls?.local[0]?.replace(/\/$/, '')
	assert(previewBase, 'Vite preview did not expose a local URL')
	baseUrl = `${previewBase}/vue-ts/?__bench`
}

const browser = await chromium.launch({ headless: true, executablePath: chromium.executablePath() })
const page = await browser.newPage()

try {
	await page.goto(baseUrl, { waitUntil: 'domcontentloaded' })
	await page.waitForFunction(() => globalThis.__benchReady === true, undefined, { timeout: READY_TIMEOUT_MS })

	const initial = await page.evaluate(() => {
		const monaco = globalThis.__monaco
		const pikaGen = monaco?.editor.getModel(monaco.Uri.parse('file:///.pikacss/pika.gen.ts'))
		return {
			body: document.body.textContent ?? '',
			pikaGenVersion: pikaGen?.getVersionId() ?? null,
			pikaGenHead: pikaGen?.getValue()
				.slice(0, 120) ?? '',
			typegenSyncRevision: globalThis.__pikaTypegenSyncRevision ?? 0,
		}
	})
	assert(initial.body.includes('.pikacss'), 'Explorer did not expose .pikacss')
	assert(initial.body.includes('pika.gen.ts'), 'Explorer did not expose pika.gen.ts')
	assert(!initial.body.includes('node_modules'), 'Explorer exposed node_modules')
	assert(initial.pikaGenVersion != null, 'Monaco did not load pika.gen.ts')
	assert(initial.pikaGenHead.includes('Auto-generated by PikaCSS'), 'pika.gen.ts model has unexpected content')

	await page.getByText('pika.gen.ts', { exact: true })
		.first()
		.click()
	const generatedEditor = await page.evaluate(() => ({
		uri: globalThis.__ed?.getModel()?.uri.toString(),
		readOnly: globalThis.__ed?.getOption(globalThis.__monaco.editor.EditorOption.readOnly),
	}))
	assert(generatedEditor.uri === 'file:///.pikacss/pika.gen.ts', 'Explorer did not open the generated Monaco model')
	assert(generatedEditor.readOnly === true, 'Generated pika.gen.ts is editable')

	await page.getByText('pika.config.ts', { exact: true })
		.first()
		.click()
	await page.evaluate((description) => {
		const monaco = globalThis.__monaco
		const editor = globalThis.__ed
		const model = editor.getModel()
		const oldText = '\'--accent\': { value: \'#34d399\' },'
		const offset = model.getValue()
			.indexOf(oldText)
		if (offset < 0)
			throw new Error('sync smoke target variable not found')
		const start = model.getPositionAt(offset)
		const end = model.getPositionAt(offset + oldText.length)
		editor.executeEdits('workspace-sync-smoke', [{
			range: new monaco.Range(start.lineNumber, start.column, end.lineNumber, end.column),
			text: `'--accent': { value: '#34d399', description: '${description}' },`,
		}])
	}, PROBE_DESCRIPTION)

	await page.waitForFunction(
		({ description, previousRevision }) => {
			const monaco = globalThis.__monaco
			const generated = monaco.editor
				.getModel(monaco.Uri.parse('file:///.pikacss/pika.gen.ts'))
			return generated?.getValue()
				.includes(description)
				&& (globalThis.__pikaTypegenSyncRevision ?? 0) > previousRevision
		},
		{ description: PROBE_DESCRIPTION, previousRevision: initial.typegenSyncRevision },
		{ timeout: 30_000 },
	)

	const regenerated = await page.evaluate(() => {
		const monaco = globalThis.__monaco
		const model = monaco.editor.getModel(monaco.Uri.parse('file:///.pikacss/pika.gen.ts'))
		return {
			version: model?.getVersionId() ?? null,
			content: model?.getValue() ?? '',
		}
	})
	assert(regenerated.version > initial.pikaGenVersion, 'pika.gen.ts Monaco model version did not advance')
	assert(regenerated.content.includes(PROBE_DESCRIPTION), 'regenerated Typegen JSDoc did not reach Monaco')

	await page.getByText('App.vue', { exact: true })
		.first()
		.click()
	await page.evaluate(() => {
		const monaco = globalThis.__monaco
		const editor = globalThis.__ed
		const model = editor.getModel()
		const offset = model.getValue()
			.indexOf('</script>')
		if (offset < 0)
			throw new Error('Vue smoke target </script> not found')
		const position = model.getPositionAt(offset)
		editor.executeEdits('workspace-sync-doc-probe', [{
			range: new monaco.Range(position.lineNumber, position.column, position.lineNumber, position.column),
			text: 'const __pikaDocProbe = pika.var[\'--accent\']\nvoid __pikaDocProbe\n',
		}])
		const targetOffset = model.getValue()
			.indexOf('\'--accent\'') + 3
		editor.setPosition(model.getPositionAt(targetOffset))
		editor.focus()
	})
	await page.keyboard.press('Escape')
	await page.evaluate(() => globalThis.__ed.getAction('editor.action.showHover')
		.run())
	await page.waitForFunction(
		description => document.querySelector('.monaco-hover')?.textContent?.includes(description),
		PROBE_DESCRIPTION,
		{ timeout: 10_000 },
	)

	const vueDx = await page.evaluate(() => ({
		hover: document.querySelector('.monaco-hover')?.textContent ?? '',
		markers: globalThis.__monaco.editor.getModelMarkers({ resource: globalThis.__ed.getModel().uri })
			.map(marker => ({ owner: marker.owner, message: marker.message })),
	}))
	assert(vueDx.hover.includes('CSS variable reference: var(--accent)'), 'Vue hover lost generated PikaCSS documentation')
	assert(vueDx.markers.length === 0, `Vue diagnostics regressed: ${JSON.stringify(vueDx.markers)}`)

	console.log('✅ playground workspace/typegen sync smoke passed')
}
finally {
	await browser.close()
	await previewServer?.close()
}
